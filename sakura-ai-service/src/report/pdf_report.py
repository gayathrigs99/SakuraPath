"""
Reusable ReportLab PDF report builder.

Only output_path and title are required. info, summary_table, sections,
and footer are all optional -- omit any of them for a simpler report.
Project-specific data fetching and scoring logic does NOT belong here --
pass already-computed data in.

Minimal usage:
    from src.report.pdf_report import build_pdf_report

    build_pdf_report(
        output_path="reports/report.pdf",
        title="My Report",
        sections=[
            {"paragraphs": ["Some text here."]},
        ],
    )

Full usage (all optional pieces included):
    build_pdf_report(
        output_path="reports/report_123.pdf",
        title="Interview Report",
        info={"Candidate": "Jane Doe", "Scenario": "Job Interview",
              "Interview ID": "abc123...", "Date": "2026-07-04"},
        summary_table=[
            ("Grammar", "8 / 10"),
            ("Politeness", "7 / 10"),
            ("Overall", "7.5 / 10"),
        ],
        sections=[
            {
                "heading": "Turn 1",
                "paragraphs": [
                    "<b>Question:</b> How are you today?",
                    "<b>Candidate:</b> I am fine, thank you.",
                ],
                "table": [["Grammar", "8/10", "Fluency", "7/10"]],
                "note": "Feedback: minor grammar slip on verb tense.",
            },
        ],
        footer="Generated by MyApp on 2026-07-04 12:00 UTC",
    )
"""

import os
from pathlib import Path
from typing import Optional, Union

from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont

def _register_report_fonts() -> tuple[str, str]:
    """Find bundled or system Japanese fonts without blocking API startup."""
    fonts_dir = Path(__file__).parent.parent.parent / "fonts"
    regular_candidates = [
        os.getenv("SAKURA_PDF_FONT_REGULAR"),
        str(fonts_dir / "NotoSansJP-Regular.ttf"),
        r"C:\Windows\Fonts\BIZ-UDGothicR.ttc",
        r"C:\Windows\Fonts\YuGothR.ttc",
        "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
        "/usr/share/fonts/truetype/noto/NotoSansJP-Regular.ttf",
    ]
    bold_candidates = [
        os.getenv("SAKURA_PDF_FONT_BOLD"),
        str(fonts_dir / "NotoSansJP-Bold.ttf"),
        r"C:\Windows\Fonts\BIZ-UDGothicB.ttc",
        r"C:\Windows\Fonts\YuGothB.ttc",
        "/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc",
        "/usr/share/fonts/truetype/noto/NotoSansJP-Bold.ttf",
    ]

    def register(alias: str, candidates: list[str | None]) -> str | None:
        for candidate in candidates:
            if not candidate or not Path(candidate).is_file():
                continue
            try:
                pdfmetrics.registerFont(TTFont(alias, candidate, subfontIndex=0))
                return alias
            except Exception:
                continue
        return None

    regular = register("SakuraJapanese", regular_candidates)
    bold = register("SakuraJapanese-Bold", bold_candidates)
    if regular:
        bold = bold or regular
        pdfmetrics.registerFontFamily(
            "SakuraJapanese", normal=regular, bold=bold, italic=regular, boldItalic=bold
        )
        return regular, bold

    # Helvetica cannot render Japanese, but keeps non-report API routes usable.
    return "Helvetica", "Helvetica-Bold"


FONT_REGULAR, FONT_BOLD = _register_report_fonts()


def build_pdf_report(
    output_path: str,
    title: str,
    info: Optional[Union[dict, list]] = None,
    summary_table: Optional[list] = None,
    sections: Optional[list] = None,
    footer: Optional[str] = None,
    accent_color: str = "#c0392b",
) -> str:
    """
    Build a styled PDF report and write it to output_path.

    info: dict or list of (label, value) pairs, rendered as a compact
        key/value table under the header (wraps two pairs per row).
    summary_table: list of (label, value) rows; the last row is
        highlighted/bolded as a totals row (e.g. an "Overall" score).
    sections: list of dicts, each optionally containing:
        - "heading": str
        - "paragraphs": list[str] (basic ReportLab markup like <b>/<i> allowed)
        - "table": list[list[str]] (a single- or multi-row grid table)
        - "col_widths": list[float] in cm, matching table columns (optional)
        - "note": str, rendered as small italic text (e.g. feedback/notes)
    footer: str shown at the bottom of the report.
    accent_color: hex color used for the title and top rule.

    Returns the output_path.
    """
    out_path = Path(output_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    doc = SimpleDocTemplate(
        str(out_path),
        pagesize=A4,
        rightMargin=2 * cm,
        leftMargin=2 * cm,
        topMargin=2 * cm,
        bottomMargin=2 * cm,
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "ReportTitle", parent=styles["Title"], fontSize=18,
        textColor=colors.HexColor(accent_color), fontName=FONT_BOLD,
    )
    heading_style = ParagraphStyle(
        "ReportHeading", parent=styles["Heading2"], fontSize=13,
        textColor=colors.HexColor("#2c3e50"), fontName=FONT_BOLD,
    )
    body_style = ParagraphStyle(
        "ReportBody", parent=styles["BodyText"], fontName=FONT_REGULAR,
    )
    label_style = ParagraphStyle(
        "ReportLabel", parent=styles["BodyText"], fontName=FONT_REGULAR,
        textColor=colors.grey, fontSize=9,
    )

    story = []

    # ---- Header (title) ----
    story.append(Paragraph(title, title_style))
    story.append(Spacer(1, 0.4 * cm))

    # ---- Info table (key/value pairs, 2 per row) ----
    if info:
        pairs = list(info.items()) if isinstance(info, dict) else list(info)
        rows = []
        for i in range(0, len(pairs), 2):
            row = list(pairs[i])
            if i + 1 < len(pairs):
                row += list(pairs[i + 1])
            else:
                row += ["", ""]
            rows.append(row)
        info_table = Table(rows, colWidths=[3 * cm, 7 * cm, 3 * cm, 5 * cm])
        info_table.setStyle(TableStyle([
            ("FONTNAME", (0, 0), (-1, -1), FONT_REGULAR),
            ("FONTNAME", (0, 0), (0, -1), FONT_BOLD),
            ("FONTNAME", (2, 0), (2, -1), FONT_BOLD),
            ("FONTSIZE", (0, 0), (-1, -1), 10),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ]))
        story.append(info_table)
        story.append(Spacer(1, 0.5 * cm))

    # ---- Summary table (last row highlighted as totals) ----
    if summary_table:
        summary_rows = [[str(a), str(b)] for a, b in summary_table]
        summary = Table(summary_rows, colWidths=[8 * cm, 4 * cm])
        summary.setStyle(TableStyle([
            ("FONTNAME", (0, 0), (-1, -2), FONT_REGULAR),
            ("FONTNAME", (0, -1), (-1, -1), FONT_BOLD),
            ("FONTSIZE", (0, 0), (-1, -1), 11),
            ("BACKGROUND", (0, -1), (-1, -1), colors.HexColor("#fadbd8")),
            ("ROWBACKGROUNDS", (0, 0), (-1, -2), [colors.whitesmoke, colors.white]),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.lightgrey),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
        ]))
        story.append(summary)
        story.append(Spacer(1, 0.6 * cm))

    # ---- Sections ----
    for section in sections or []:
        heading = section.get("heading")
        if heading:
            story.append(Paragraph(heading, heading_style))
            story.append(Spacer(1, 0.2 * cm))

        for para in section.get("paragraphs", []):
            story.append(Paragraph(para, body_style))
        if section.get("paragraphs"):
            story.append(Spacer(1, 0.1 * cm))

        table_data = section.get("table")
        if table_data:
            col_widths = section.get("col_widths")
            col_widths_pt = [w * cm for w in col_widths] if col_widths else None
            sec_table = Table(table_data, colWidths=col_widths_pt)
            n_cols = len(table_data[0]) if table_data else 0
            bold_cols = [("FONTNAME", (c, 0), (c, -1), FONT_BOLD) for c in range(0, n_cols, 2)]
            sec_table.setStyle(TableStyle([
                ("FONTNAME", (0, 0), (-1, -1), FONT_REGULAR),
                *bold_cols,
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("GRID", (0, 0), (-1, -1), 0.3, colors.lightgrey),
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f9f9f9")),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
            ]))
            story.append(sec_table)

        note = section.get("note")
        if note:
            story.append(Spacer(1, 0.1 * cm))
            story.append(Paragraph(f"<i>{note}</i>", label_style))

        story.append(Spacer(1, 0.4 * cm))

    # ---- Footer (optional) ----
    if footer:
        story.append(Spacer(1, 0.2 * cm))
        story.append(Paragraph(footer, label_style))

    doc.build(story)
    return str(out_path)
